var chinaIPNets []*net.IPNet

func init() {
	// 启动时解析CIDR列表到IPNet对象，避免运行时重复解析
	chinaIPNets = make([]*net.IPNet, 0, len(chinaCIDRs))
	for _, cidr := range chinaCIDRs {
		_, ipNet, err := net.ParseCIDR(cidr)
		if err == nil {
			chinaIPNets = append(chinaIPNets, ipNet)
		}
	}
}

// IsIPFromChina 判断给定IP是否来自中国大陆
func IsIPFromChina(ipStr string) bool {
	// 处理IPv6映射的IPv4地址 (::ffff:192.168.1.1)
	if strings.HasPrefix(ipStr, "::ffff:") {
		ipStr = strings.TrimPrefix(ipStr, "::ffff:")
	}

	ip := net.ParseIP(ipStr)
	if ip == nil {
		return false // 无效IP，默认当作境外
	}

	// 遍历中国IP段，匹配任意一个即返回true
	for _, ipNet := range chinaIPNets {
		if ipNet.Contains(ip) {
			return true
		}
	}

	return false
}
